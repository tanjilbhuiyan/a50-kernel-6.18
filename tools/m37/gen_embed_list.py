#!/usr/bin/env python3
"""M3.7: turn the Halium ramdisk into a gen_init_cpio list, plus our /a50 diagnostics.

  gen_embed_list.py RAMDISK_GZ ROOT_DIR OUT_LIST

Regular files are written under ROOT_DIR. Directories, symlinks and device
nodes become list entries. The output is a template for tools/m22_build.sh.
"""
import gzip
import os
import shutil
import stat
import sys

rd, root, out = sys.argv[1:4]
a = gzip.decompress(open(rd, "rb").read())
shutil.rmtree(root, ignore_errors=True)
os.makedirs(root)

# newc hardlinks: every name has the same inode, and only one entry carries the data.
links, payload = {}, {}
pos = 0
while True:
    f = [int(a[pos + 6 + 8 * i:pos + 14 + 8 * i], 16) for i in range(13)]
    name = a[pos + 110:pos + 110 + f[11] - 1].decode()
    data = (pos + 110 + f[11] + 3) & ~3
    if name == "TRAILER!!!":
        break
    if stat.S_ISREG(f[1]) and f[4] > 1:
        links.setdefault(f[0], []).append("/" + name.lstrip("./"))
        if f[6]:
            payload[f[0]] = a[data:data + f[6]]
    pos = (data + f[6] + 3) & ~3

entries, seen, counts, done = [], set(), {}, set()
pos = 0
while True:
    if a[pos:pos + 6] != b"070701":
        sys.exit(f"bad cpio magic at {pos}")
    f = [int(a[pos + 6 + 8 * i:pos + 14 + 8 * i], 16) for i in range(13)]
    ino, mode, nlink, fsize, rmaj, rmin, nsize = f[0], f[1], f[4], f[6], f[9], f[10], f[11]
    name = a[pos + 110:pos + 110 + nsize - 1].decode()
    data = (pos + 110 + nsize + 3) & ~3
    if name == "TRAILER!!!":
        break
    pos = (data + fsize + 3) & ~3
    if name in (".", ""):
        continue
    path = "/" + name.lstrip("./")
    perm = f"{stat.S_IMODE(mode):04o}"
    seen.add(path)
    if stat.S_ISDIR(mode):
        kind = "dir"; entries.append(f"dir {path} {perm} 0 0")
    elif stat.S_ISLNK(mode):
        kind = "slink"; entries.append(f"slink {path} {a[data:data + fsize].decode()} {perm} 0 0")
    elif stat.S_ISCHR(mode) or stat.S_ISBLK(mode):
        kind = "nod"; entries.append(f"nod {path} {perm} 0 0 {'c' if stat.S_ISCHR(mode) else 'b'} {rmaj} {rmin}")
    elif stat.S_ISREG(mode) and nlink > 1:
        kind = "hardlink"
        if ino not in done:
            done.add(ino)
            if ino not in payload:
                sys.exit(f"no data for hardlink group of {path}")
            src = os.path.join(root, f"f{len(entries)}")
            with open(src, "wb") as w:
                w.write(payload[ino])
            entries.append(f"file {path} {src} {perm} 0 0 " + " ".join(n for n in links[ino] if n != path))
    elif stat.S_ISREG(mode):
        kind = "file"
        src = os.path.join(root, f"f{len(entries)}")
        with open(src, "wb") as w:
            w.write(a[data:data + fsize])
        entries.append(f"file {path} {src} {perm} 0 0")
    else:
        kind = "skip"
    counts[kind] = counts.get(kind, 0) + 1

ours = ["dir /dev 0755 0 0", "dir /proc 0755 0 0", "dir /sys 0755 0 0", "dir /tmp 0755 0 0", "dir /a50 0755 0 0",
        "nod /dev/console 0600 0 0 c 5 1", "nod /dev/null 0666 0 0 c 1 3",
        "file /a50/busybox @REPO@/src/m22/busybox 0755 0 0", "file /a50/init @REPO@/tools/m22/init 0755 0 0",
        "file /a50/manifest @REPO@/src/m36/halium-manifest.txt 0644 0 0"]
final = [e for e in ours if e.split()[1] not in seen] + entries
with open(out, "w") as w:
    w.write("# Generated by tools/m37/gen_embed_list.py\n" + "\n".join(final) + "\n")
print(counts, "list lines", len(final))
