#!/usr/bin/env python3
"""M4.3: generate the S2MPU09 regulator table and DT nodes from Samsung's sources.

  gen_table.py SAMSUNG_TREE STOCK_DTBO_DTS BASELINE_TABLE OUT_H OUT_DTSI

The register table comes from Samsung's active regulator list (commented-out
entries are skipped). Names and flags come from the stock DT, and min/max
from the live baseline regulator table.
"""
import re
import sys

samsung, dts, baseline, out_h, out_dtsi = sys.argv[1:6]
src = open(f"{samsung}/drivers/regulator/s2mpu09-regulator.c").read()
hdr = open(f"{samsung}/include/linux/mfd/samsung/s2mpu09-regulator.h").read()
src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
table = src[src.index("regulators[S2MPU09_REGULATOR_MAX] = {"):]
table = table[:table.index("};")]
defs = dict(re.findall(r"#define\s+(S2MPU09_\w+)\s+(0x[0-9A-Fa-f]+|\d+)", hdr))


def val(name):
    return int(defs[name], 0)


regs = []
for kind, name, _, mn, st, vs, en in re.findall(
        r'(BUCK|LDO)_DESC\("(\w+)",\s*_\w+\((\d+)\),\s*&\w+\(\),\s*_\w+\((_MIN\d)\),\s*_\w+\((_STEP\d)\),\s*_REG\((_\w+)\),\s*_REG\((_\w+)\)', table):
    regs.append((name, kind, val(f"S2MPU09_{kind}{mn}"), val(f"S2MPU09_{kind}{st}"),
                 val(f"S2MPU09_PMIC_REG{vs}"), val(f"S2MPU09_PMIC_REG{en}")))
if not regs:
    sys.exit("empty regulator table")

base = {}
for line in open(baseline):
    p = line.rstrip("\n").split("|")
    if len(p) == 6:
        base[p[0]] = p

text = open(dts).read()
block = text[text.index("regulators {", text.index("s2mpu09mfd")):]
nodes = {}
for name, body in re.findall(r"\n\s+((?:BUCK|LDO)\w*) \{\n(.*?)\n\s+\};", block, re.S):
    if name in nodes:
        continue
    m = re.search(r'regulator-name = "([^"]+)"', body)
    if m:
        nodes[name] = (m.group(1), "regulator-always-on" in body, "regulator-boot-on" in body)

with open(out_h, "w") as f:
    f.write("/* Generated by tools/m43/gen_table.py from Samsung's s2mpu09-regulator.c. */\n")
    f.write("static const struct s2mpu09_acpm_reg s2mpu09_regs[] = {\n")
    for name, kind, mn, st, vs, en in regs:
        f.write(f'\t{{ "{name}", {"true" if kind == "BUCK" else "false"}, {mn}, {st}, 0x{vs:02x}, 0x{en:02x} }},\n')
    f.write("};\n")

missing = [r[0] for r in regs if r[0] not in nodes]
skipped, count = [], 0
with open(out_dtsi, "w") as f:
    f.write("/* Generated by tools/m43/gen_table.py. */\n")
    for name, *_ in regs:
        if name not in nodes:
            continue
        rname, always, boot = nodes[name]
        if rname not in base or not base[rname][4] or not base[rname][5]:
            skipped.append(name)
            continue
        label = name.lower() + "_reg"
        f.write(f'\t\t\t\t{label}: {name} {{\n\t\t\t\t\tregulator-name = "{rname}";\n')
        f.write(f"\t\t\t\t\tregulator-min-microvolt = <{base[rname][4]}>;\n\t\t\t\t\tregulator-max-microvolt = <{base[rname][5]}>;\n")
        if always:
            f.write("\t\t\t\t\tregulator-always-on;\n")
        if boot:
            f.write("\t\t\t\t\tregulator-boot-on;\n")
        f.write("\t\t\t\t};\n")
        count += 1
print(f"table {len(regs)}, DT nodes {count}, no stock node {missing}, not in baseline {skipped}")
