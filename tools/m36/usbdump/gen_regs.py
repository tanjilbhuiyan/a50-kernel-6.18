#!/usr/bin/env python3
"""Generate regs.h for a50_usbdump.c from the kernel sources.

  gen_regs.py SAMSUNG_4_14_TREE ACK_6_18_COMMON_TREE OUT_REGS_H

PHY list: EXYNOS_USBCON_* below 0x100 in Samsung's register header, minus
debug/history and the CR access window. CMU_USB list: exactly the registers in
the 6.18 clock driver's usb_clk_regs[] table.
"""
import re
import sys

samsung, ack, out = sys.argv[1:4]

SKIP = {"LINK_DEBUG_L", "LINK_DEBUG_H", "LTSTATE_HIS", "SSP_CRCTL0", "SSP_CRCTL1"}
text = open(f"{samsung}/drivers/phy/samsung/phy-exynos-usb3p1-reg.h").read()
phy = []
for name, off in re.findall(r"^#define\s+EXYNOS_USBCON_([A-Z0-9_]+)\s+\((0x[0-9a-fA-F]+)\)", text, re.M):
    if int(off, 16) < 0x100 and name not in SKIP:
        phy.append((name, int(off, 16)))

text = open(f"{ack}/drivers/clk/samsung/clk-exynos9610.c").read()
defines = dict(re.findall(r"^#define\s+([A-Z0-9_]+)\s+(0x[0-9a-fA-F]+)\s*$", text, re.M))
table = re.search(r"usb_clk_regs\[\][^{]*\{(.*?)\};", text, re.S).group(1)
cmu = [(n, int(defines[n], 16)) for n in re.findall(r"[A-Z][A-Z0-9_]+", table)]
if not phy or not cmu:
    sys.exit("empty register list")

with open(out, "w") as f:
    f.write("/* Generated by gen_regs.py. */\n")
    for var, regs in (("phy_regs", phy), ("cmu_usb_regs", cmu)):
        f.write(f"static const struct a50_reg {var}[] = {{\n")
        for name, off in regs:
            f.write(f'\t{{ "{name}", 0x{off:x} }},\n')
        f.write("};\n")
print(f"phy {len(phy)} regs, cmu_usb {len(cmu)} regs")
